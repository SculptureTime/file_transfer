const fs = require('node:fs')
const path = require('node:path')

// 将已有依赖和 Worker 代码打包为本地页面可加载的脚本，避免 file:// 外部 Worker 限制。
const root = path.resolve(__dirname, '..')
const libraries = ['pako.min.js', 'qrcode-generator.min.js', 'jsQR.min.js']
const sources = libraries.map((name) => fs.readFileSync(path.join(root, 'js', name), 'utf8'))
const worker = fs.readFileSync(path.join(root, 'js/qr-worker-v2.js'), 'utf8').replace(/^importScripts\([^\n]+\);\r?\n/m, '')
sources.push(worker)
const bundle = '// Generated by scripts/build-worker.cjs; do not edit.\n' + 'globalThis.qrWorkerSource = ' + JSON.stringify(sources.join('\n;\n')) + '\n'
fs.writeFileSync(path.join(root, 'js/qr-worker-inline.js'), bundle)
